#!/bin/bash
# Builds the macOS helper (transcription, capture, text extraction) into native/bin/machete-native
# and exports the menu bar icon (SF Symbol "sparkles", same as the native app).
set -euo pipefail
cd "$(dirname "$0")/.."
[[ "$(uname)" == "Darwin" ]] || { echo "machete-native is macOS-only; skipping."; exit 0; }
(cd native && swift build -c release 2>&1 | grep -E "error|Build complete" || true)
mkdir -p native/bin
cp native/.build/release/machete-native native/bin/machete-native
codesign --force --sign - native/bin/machete-native >/dev/null 2>&1 || true
native/bin/machete-native icon sparkles 15 assets/trayTemplate.png 1
native/bin/machete-native icon sparkles 15 assets/trayTemplate@2x.png 2
echo "native helper ready: native/bin/machete-native"

# SF Symbols used by the overlay, exported at the sizes/weights the SwiftUI views use, plus a CSS file
# with their point sizes so the renderer draws them as masks in any color.
mkdir -p assets/icons
CSS=assets/icons/icons.css
echo "/* generated by scripts/build-native.sh */" > "$CSS"
while read -r cls symbol pt weight; do
  [[ -z "$cls" ]] && continue
  out="assets/icons/$cls.png"
  native/bin/machete-native icon "$symbol" "$pt" "$out" 3 "$weight"
  w=$(sips -g pixelWidth "$out" | awk '/pixelWidth/ {print $2}')
  h=$(sips -g pixelHeight "$out" | awk '/pixelHeight/ {print $2}')
  printf '.i-%s { width: %spx; height: %spx; -webkit-mask: url("%s.png") center / contain no-repeat; background: currentColor; display: inline-block; flex: none; }\n' \
    "$cls" "$(echo "scale=2; $w/3" | bc)" "$(echo "scale=2; $h/3" | bc)" "$cls" >> "$CSS"
done <<'ICONS'
arrow-left arrow.left 17 medium
arrow-down arrow.down 17 medium
binoculars binoculars 16 regular
binoculars-fill binoculars.fill 16 regular
grid square.grid.2x2 15 regular
eye eye 16 regular
eye-slash eye.slash 16 regular
waveform waveform 16 regular
copy doc.on.doc 12 regular
doc-text doc.text 12 medium
doc-plus doc.badge.plus 18 regular
ICONS
echo "icons ready: $(ls assets/icons/*.png | wc -l | tr -d ' ') symbols"
