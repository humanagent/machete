import AppKit

/// Clipboard history: notices new text on the clipboard and pastes a chosen entry back.
/// Text only; whatever a password manager marks as concealed or transient is never seen.
enum Clipboard {
    /// The nspasteboard.org markers: passwords, one-off values, and Machete's own dictation paste.
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let skipped: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        transient,
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]
    /// Longer copies (a whole file, a log) aren't kept.
    private static let maxLength = 100_000

    @MainActor private static var timer: Timer?
    @MainActor private static var lastChange = NSPasteboard.general.changeCount

    /// While true the watch ignores what happens on the clipboard (Machete is borrowing it).
    @MainActor static var paused = false

    @MainActor static func resume() {
        lastChange = NSPasteboard.general.changeCount
        paused = false
    }

    typealias Contents = [[NSPasteboard.PasteboardType: Data]]

    @MainActor static func save() -> Contents {
        NSPasteboard.general.pasteboardItems?.map { item in
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types { if let v = item.data(forType: t) { d[t] = v } }
            return d
        } ?? []
    }

    @MainActor static func restore(_ saved: Contents) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.writeObjects(saved.map { d in
            let item = NSPasteboardItem()
            for (t, v) in d { item.setData(v, forType: t) }
            return item
        })
    }

    /// Checks the clipboard's change counter twice a second; it only reads the text when the counter moved.
    @MainActor static func watch(_ onText: @escaping (String) -> Void) {
        timer?.invalidate()
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated {
                let pb = NSPasteboard.general
                guard !paused, pb.changeCount != lastChange else { return }
                lastChange = pb.changeCount
                let types = Set(pb.types ?? [])
                guard types.isDisjoint(with: skipped), let text = pb.string(forType: .string) else { return }
                guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= maxLength else { return }
                onText(text)
            }
        }
    }

    /// Puts `text` on the clipboard and sends ⌘V to the app in front. It stays on the clipboard, like a copy.
    @MainActor static func paste(_ text: String) -> Bool {
        guard Dictation.canType(prompt: true) else { return false }
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        let src = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let e = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: down) // V
            e?.flags = .maskCommand
            e?.post(tap: .cghidEventTap)
        }
        return true
    }
}
