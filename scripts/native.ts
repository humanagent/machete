// Builds the macOS helper (native/ → native/bin/machete-native) and exports the SF Symbols the UI uses
// (assets/trayTemplate*.png and assets/icons/*.png + icons.css). macOS only; a no-op elsewhere.
import { mkdir } from 'node:fs/promises';
import { $ } from 'bun';

if (process.platform !== 'darwin') {
  console.log('machete-native is macOS-only; skipping.');
  process.exit(0);
}

const root = new URL('..', import.meta.url).pathname;
const helper = `${root}native/bin/machete-native`;

await $`swift build -c release`.cwd(`${root}native`).quiet();
await mkdir(`${root}native/bin`, { recursive: true });
await $`cp ${root}native/.build/release/machete-native ${helper}`;
await $`codesign --force --sign - ${helper}`.quiet().nothrow();
await $`${helper} icon sparkles 15 ${root}assets/trayTemplate.png 1`;
await $`${helper} icon sparkles 15 ${root}assets/trayTemplate@2x.png 2`;
console.log('native helper ready: native/bin/machete-native');

/** class, SF Symbol, point size, weight: the sizes the panel draws them at. */
const ICONS: ReadonlyArray<readonly [string, string, number, string]> = [
  ['arrow-left', 'arrow.left', 17, 'medium'],
  ['arrow-down', 'arrow.down', 17, 'medium'],
  ['binoculars', 'binoculars', 16, 'regular'],
  ['binoculars-fill', 'binoculars.fill', 16, 'regular'],
  ['grid', 'square.grid.2x2', 15, 'regular'],
  ['eye', 'eye', 16, 'regular'],
  ['eye-slash', 'eye.slash', 16, 'regular'],
  ['waveform', 'waveform', 16, 'regular'],
  ['copy', 'doc.on.doc', 12, 'regular'],
  ['doc-text', 'doc.text', 12, 'medium'],
  ['doc-plus', 'doc.badge.plus', 18, 'regular'],
];
const SCALE = 3;

await mkdir(`${root}assets/icons`, { recursive: true });
const css = ['/* generated by scripts/native.ts */'];
for (const [cls, symbol, pt, weight] of ICONS) {
  const out = `${root}assets/icons/${cls}.png`;
  await $`${helper} icon ${symbol} ${pt} ${out} ${SCALE} ${weight}`;
  const info = await $`sips -g pixelWidth -g pixelHeight ${out}`.text();
  const px = (key: string) => Number(info.match(new RegExp(`${key}: (\\d+)`))?.[1] ?? 0) / SCALE;
  css.push(
    `.i-${cls} { width: ${px('pixelWidth').toFixed(2)}px; height: ${px('pixelHeight').toFixed(2)}px; -webkit-mask: url("${cls}.png") center / contain no-repeat; background: currentColor; display: inline-block; flex: none; }`,
  );
}
await Bun.write(`${root}assets/icons/icons.css`, `${css.join('\n')}\n`);
console.log(`icons ready: ${ICONS.length} symbols`);
